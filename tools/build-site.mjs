#!/usr/bin/env node
// Build the static site for GitHub Pages into _site/ (M1 design 3.7):
// the app, the engine, the framework, the demo world, and a service worker that precaches all of it
// so worlds stay playable offline. Player books and worlds (library/, worlds/) are never included.
// Usage: node tools/build-site.mjs [outDir]   (default _site)

import { cpSync, existsSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { join, relative, sep } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const out = join(root, process.argv[2] ?? "_site");

// What the site serves; everything else in the repository stays out
const INCLUDE = ["index.html", "manifest.webmanifest", "LICENSE", "app", "engine", "framework", "examples/openstax-kinematics"];

function listFiles(dir) {
  return readdirSync(dir).flatMap((name) => {
    const path = join(dir, name);
    return statSync(path).isDirectory() ? listFiles(path) : [path];
  });
}

/** Service worker source: precache every file, answer from the cache first, drop old caches. */
export function serviceWorker(version, files) {
  return `// Generated by tools/build-site.mjs. Do not edit.
const CACHE = "expert-quest-${version}";
const FILES = ${JSON.stringify(files)};

self.addEventListener("install", (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(FILES)).then(() => self.skipWaiting()));
});

self.addEventListener("activate", (e) => {
  e.waitUntil(caches.keys()
    .then((keys) => Promise.all(keys.filter((k) => k.startsWith("expert-quest-") && k !== CACHE).map((k) => caches.delete(k))))
    .then(() => self.clients.claim()));
});

// Same-origin GETs come from the cache when present (query strings such as ?world= are ignored);
// anything else, such as a class world fetched from another site, goes to the network.
self.addEventListener("fetch", (e) => {
  const req = e.request;
  if (req.method !== "GET" || new URL(req.url).origin !== location.origin) return;
  e.respondWith(caches.match(req, { ignoreSearch: true }).then((hit) => hit ?? fetch(req)));
});
`;
}

export function buildSite(outDir = out) {
  rmSync(outDir, { recursive: true, force: true });
  mkdirSync(outDir, { recursive: true });
  for (const item of INCLUDE) {
    const src = join(root, item);
    if (!existsSync(src)) throw new Error(`missing ${item}`);
    cpSync(src, join(outDir, item), { recursive: true });
  }
  // Pages would otherwise run Jekyll and skip files starting with an underscore
  writeFileSync(join(outDir, ".nojekyll"), "");

  const files = listFiles(outDir).filter((f) => !f.endsWith(".nojekyll")).sort();
  const hash = createHash("sha256");
  for (const f of files) hash.update(relative(outDir, f)).update(readFileSync(f));
  const version = hash.digest("hex").slice(0, 12);
  const urls = files.map((f) => relative(outDir, f).split(sep).join("/"));
  // Directory URLs are what people open, so cache them too
  urls.push("./", "app/", "engine/");
  writeFileSync(join(outDir, "sw.js"), serviceWorker(version, urls));
  return { version, files: urls.length };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const { version, files } = buildSite();
  console.log(`site built in ${relative(root, out)}: ${files} files, version ${version}`);
}
